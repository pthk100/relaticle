    /**
     * @return array<string, string>
     */
    public static function countries(): array
    {
        return self::COUNTRIES;
    }

    /**
     * IANA time zone identifiers, with "GMT" first as the explicit unknown.
     * A contact whose zone is genuinely unknown gets GMT; the field cannot
     * default itself (the settings vocabulary has no default_value), so the
     * write path supplies it.
     *
     * @return array<string, string>
     */
    public static function timezones(): array
    {
        $zones = ['GMT' => 'GMT'];

        foreach (DateTimeZone::listIdentifiers(DateTimeZone::ALL) as $zone) {
            $zones[$zone] = $zone;
        }

        return $zones;
    }
